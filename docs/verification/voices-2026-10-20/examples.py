"""
Brief 16's examples, read from the runs, never typed (section 11: "before/after examples from actual rendered gameplay",
"consecutive feedback transcripts showing improvement, repetition, and recovery over time", "examples demonstrating
distinct teaching voices", "Profile recommendations before and after"). Each is the same student on the same seed, before
(`before/`, the baseline's code) and after (`after/`, the tested commit), so the play is the same and only the words
differ (`same-play.py`).

    python3 docs/verification/voices-2026-10-20/examples.py > docs/verification/voices-2026-10-20/examples.md
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
load = lambda side, s: json.load(open(os.path.join(HERE, side, f'{s}.json')))
out = []
w = out.append


def showings(run, course, since='', until='9999'):
    return [x for x in run['said'] if x['kind'] == 'showing' and x['course'] == course and since <= x['at'] <= until]


def side_by_side(title, scenario, course, since='', until='9999', limit=14):
    b, a = load('before', scenario), load('after', scenario)
    sb, sa = showings(b, course, since, until)[:limit], showings(a, course, since, until)[:limit]
    w(f'### {title}\n')
    w(f'The {scenario} student, seed v16-0, {course}, every showing in order{f" from {since}" if since else ""}. Same day, same band, same note (`same-play.py`); the words before, then after.\n')
    for x, y in zip(sb, sa):
        assert (x['at'], x['band'], x['note']) == (y['at'], y['band'], y['note'])
        w(f'- **{x["at"]}, {x["piece"]}, {x["band"].capitalize()}** ({x["note"].replace(":", ", ")})')
        w(f'  - Before: {x["text"]}')
        w(f'  - After: {y["text"]}')
    w('')


w('# Brief 16: Examples From The Runs\n')
w('Generated by `examples.py` from `before/` and `after/`. Nothing here is typed: each line is what the game said to a played student, on the baseline\'s code and on the tested commit.\n')

w('## Consecutive Feedback: Improvement, Repetition, Recovery\n')
side_by_side('A Student Who Improves After Feedback', 'improving', 'Acting I', until='2027-04-30')
side_by_side('A Student Who Resolves A Note And Regresses', 'regressing', 'Voice I')
side_by_side('A Highly Skilled Student Maintaining Strong Work', 'skilled', 'Speech And Accents I')
side_by_side('An Underprepared Student With Recurring Notes', 'underprepared', 'Acting I', until='2027-03-31', limit=10)

w('## Distinct Voices\n')
w('The first Strong piece with nothing holding it back in each of four courses, one of each discipline, from the attentive student. Before, each heard "It came together. Here’s what to try next." and acting\'s step; after, its own.\n')
for course in ['Acting I', 'Voice I', 'The Body As Source I', 'Text And Context Across The Repertory', 'Speech And Accents I', 'Alexander Technique I']:
    for side in ['before', 'after']:
        run = load(side, 'attentive')
        first = next((x for x in showings(run, course) if x['note'].startswith('advanced') and x['band'] in ('strong', 'exceptional')), None)
        if first:
            w(f'- **{course}, {side}** ({first["at"]}): {first["text"]}')
w('')
w('A piece under Strong, prepared, and held back by a limit, in two disciplines (the regressing student):\n')
for course in ['Voice I', 'Acting I']:
    for side in ['before', 'after']:
        run = load(side, 'regressing')
        first = next((x for x in showings(run, course) if x['note'].startswith('advanced') and x['band'] in ('working', 'unready')), None)
        if first:
            w(f'- **{course}, {side}** ({first["at"]}): {first["text"]}')
w('')

w('## Directors\n')
w('Each note a director gave the attentive student, in order: before, then after.\n')
b, a = load('before', 'attentive'), load('after', 'attentive')
for x, y in zip([x for x in b['said'] if x['kind'] == 'director'], [x for x in a['said'] if x['kind'] == 'director']):
    w(f'- **{x["at"]}**')
    w(f'  - Before: {x["text"]}')
    w(f'  - After: {y["text"]}')
w('')

w('## Classmates Who Come Back\n')
w('Every notice from a classmate the underprepared student had before, said again word for word in the baseline, and what the same moment says after.\n')
b, a = load('before', 'underprepared'), load('after', 'underprepared')
nb = [x for x in b['said'] if x['kind'] == 'notice' and re.search(r'Didn’t Come|A Request For Help|Run Lines Together|An Apology', x.get('title', ''))]
na = [x for x in a['said'] if x['kind'] == 'notice' and re.search(r'Didn’t Come|A Request For Help|Run Lines Together|An Apology', x.get('title', ''))]
seen = {}
for x, y in zip(nb, na):
    seen[x['text']] = seen.get(x['text'], 0) + 1
    if seen[x['text']] >= 2:
        w(f'- **{x["at"]}, {x["title"]}**')
        w(f'  - Before (said before, word for word): {x["text"]}')
        w(f'  - After: {y["text"]}')
w('')

w('## The Profile’s What To Work On Next\n')
w('The attentive student\'s, on the first Sunday in 2027 with work to advise on. Before, every recommendation\'s whole reasoning was shown; after, the card shows what\'s under the heading, and the rest is behind Why This Recommendation.\n')
for side in ['before', 'after']:
    run = load(side, 'attentive')
    adv = next(x for x in run['said'] if x['kind'] == 'advice' and x['at'] >= '2027-01-01')
    shown = adv['text']
    w(f'### {side.capitalize()} ({adv["at"]}), {len(shown.split())} words shown\n')
    for line in shown.split('\n'):
        w(f'> {line}\n>')
    if adv.get('details'):
        w(f'\nBehind Why This Recommendation, {len(adv["details"].split())} words:\n')
        for line in adv['details'].split('\n'):
            w(f'> {line}\n>')
    w('')

print('\n'.join(out))
