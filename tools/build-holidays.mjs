/**
 * Builds SLATE's public-holiday files from the date-holidays dataset.
 *
 * One file per country in `public/holidays/<id>.tsv`, fetched only when the
 * player is standing in that country, the same way the city lists work.
 * Each row is one holiday on one date:
 *
 *   date  local name  english name  type  region
 *
 * `type` is what the dataset calls it: public (a day off), bank, school,
 * optional, or observance (Valentine's Day is on the calendar; nobody gets
 * the day off). `region` is empty for a national holiday and the ISO 3166-2
 * subdivision code for one that only a state or province keeps.
 *
 * The local name is how the day is written on a calendar in that country;
 * the English name is there for the player who does not read it. Where the
 * dataset has no separate English name, both columns carry the same text.
 *
 * Run with: node tools/build-holidays.mjs [fromYear] [toYear]
 */

import { writeFileSync, mkdirSync, readdirSync, unlinkSync } from 'node:fs';
import { join } from 'node:path';
import Holidays from 'date-holidays';

const FROM = Number(process.argv[2] ?? 2026);
const TO = Number(process.argv[3] ?? 2045);
const COUNTRY_ID_OVERRIDE = { GB: 'uk' };
const countryId = (iso2) => COUNTRY_ID_OVERRIDE[iso2] ?? iso2.toLowerCase();

const catalogue = new Holidays();
const countries = Object.keys(catalogue.getCountries()).sort();

const outDir = 'public/holidays';
mkdirSync(outDir, { recursive: true });
for (const f of readdirSync(outDir)) if (f.endsWith('.tsv')) unlinkSync(join(outDir, f));

const clean = (s) => String(s ?? '').replace(/[\t\n\r]+/g, ' ').trim();
const dayOf = (h) => String(h.date).slice(0, 10);

/** Every holiday for one place, across the years, as rows keyed for de-duplication. */
function rowsFor(iso2, state, region) {
  const local = new Holidays(iso2, state ?? undefined);
  const english = new Holidays(iso2, state ?? undefined, { languages: ['en'] });
  const out = new Map();
  for (let year = FROM; year <= TO; year++) {
    let mine = [];
    let en = [];
    try { mine = local.getHolidays(year) || []; en = english.getHolidays(year) || []; } catch { continue; }
    const enByKey = new Map(en.map((h) => [`${dayOf(h)}|${h.rule ?? h.name}`, h]));
    for (const h of mine) {
      if (!h.name) continue;
      const day = dayOf(h);
      const match = enByKey.get(`${day}|${h.rule ?? h.name}`);
      const key = `${day}|${clean(h.name)}|${region}`;
      if (out.has(key)) continue;
      out.set(key, [day, clean(h.name), clean(match?.name ?? h.name), h.type ?? 'public', region]);
    }
  }
  return out;
}

const manifest = [];
let total = 0;
for (const iso2 of countries) {
  const id = countryId(iso2);
  const national = rowsFor(iso2, null, '');
  const nationalKeys = new Set([...national.keys()].map((k) => k.split('|').slice(0, 2).join('|')));
  const rows = [...national.values()];

  // Subdivision holidays: only what the state keeps that the country does not.
  const states = catalogue.getStates(iso2) || {};
  for (const code of Object.keys(states).sort()) {
    const regional = rowsFor(iso2, code, code);
    for (const [key, row] of regional) {
      if (nationalKeys.has(key.split('|').slice(0, 2).join('|'))) continue;
      rows.push(row);
    }
  }
  if (rows.length === 0) continue;
  rows.sort((a, b) => a[0].localeCompare(b[0]) || a[4].localeCompare(b[4]) || a[1].localeCompare(b[1]));
  // The subdivisions this file knows, so a state can be matched by name as
  // well as by code: "# CA\tCalifornia".
  const header = Object.entries(states).sort().map(([code, name]) => `# ${code}\t${clean(name)}`);
  writeFileSync(join(outDir, `${id}.tsv`), [...header, ...rows.map((r) => r.join('\t'))].join('\n'));
  manifest.push([id, rows.length, Object.keys(states).length]);
  total += rows.length;
}

const ts = `/**
 * SLATE — which countries have a holiday file on disk, and how big it is.
 *
 * Generated by tools/build-holidays.mjs from the date-holidays dataset
 * (ISC / CC-BY-3.0). The files themselves live in public/holidays and are
 * fetched a country at a time; see src/engine/content/holidays.ts.
 */

/** countryId → [rows on file, subdivisions with their own holidays]. */
export const HOLIDAY_FILES: Readonly<Record<string, readonly [number, number]>> = Object.fromEntries(
  ${JSON.stringify(manifest.map((m) => m.join('\t')).join('\n'))}.split('\\n').map((line) => {
    const [id, rows, regions] = line.split('\\t');
    return [id as string, [Number(rows), Number(regions)] as const];
  }),
);

/** The years the files cover, inclusive. */
export const HOLIDAY_YEARS: readonly [number, number] = [${FROM}, ${TO}];
`;
writeFileSync('src/engine/content/holiday-data.ts', ts);
console.log(`countries ${manifest.length}, rows ${total}, years ${FROM}-${TO}`);
