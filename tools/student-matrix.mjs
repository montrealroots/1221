/**
 * SLATE — the student-experience matrix, rendered from its data and checked against the evidence (from 2026-10-10).
 *
 * docs/verification/student-matrix.json holds a row per thing the player needs to accomplish in School, Banking and
 * Papers. This checks each row's evidence before it says anything: every command it names is registered in the
 * engine, and every test it cites is in its file, by its title. A row is Evidenced only when all of that is found;
 * otherwise Missing Evidence, said, and --check fails. The count can't be raised by typing: a row's status is worked
 * out here, not written in the data. The 16 deferred items are listed apart, out of the count.
 *
 * From 2026-10-10 each row carries acceptance assertions, each an outcome and the downstream system that reads it, with
 * the test that asserts it; and the statuses are the brief's: Behaviorally Verified where every assertion's test is
 * found, Simplified With A Boundary where it's verified and says where SLATE stops short, Implemented where the
 * commands are there and an assertion's test isn't, Blocked where the row says so. A row that changed keeps its old
 * limitation as `before`, rendered beside the new.
 *
 *   node tools/student-matrix.mjs --write   renders docs/verification/STUDENT-MATRIX.md
 *   node tools/student-matrix.mjs --check   fail on missing evidence, or a document out of date
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const data = JSON.parse(readFileSync('docs/verification/student-matrix.json', 'utf8'));
const out = 'docs/verification/STUDENT-MATRIX.md';

// Every command the engine registers, read from its source.
const engine = [];
const walk = (dir) => { for (const f of readdirSync(dir, { withFileTypes: true })) { const p = join(dir, f.name); if (f.isDirectory()) walk(p); else if (p.endsWith('.ts')) engine.push(readFileSync(p, 'utf8')); } };
walk('src/engine');
const registered = new Set([...engine.join('\n').matchAll(/onCommand<[^>]*(?:<[^>]*>[^>]*)*>\('([a-z_.]+)'/g)].map((m) => m[1]));
const fallback = engine.join('\n');

const rows = data.features.map((f) => {
  const missing = [];
  for (const c of f.commands) if (!registered.has(c) && !fallback.includes(`'${c}'`)) missing.push(`command ${c}`);
  for (const t of f.tests) {
    if (!existsSync(t.file)) { missing.push(`test file ${t.file}`); continue; }
    const text = readFileSync(t.file, 'utf8');
    if (t.title && !text.includes(t.title)) missing.push(`test “${t.title}” in ${t.file}`);
  }
  if (!f.tests.length) missing.push('no test cited');
  const unasserted = [];
  for (const a of f.acceptance ?? []) {
    if (!existsSync(a.file) || !readFileSync(a.file, 'utf8').includes(a.title)) unasserted.push(`assertion “${a.title}” in ${a.file}`);
  }
  if (!(f.acceptance ?? []).length) unasserted.push('no acceptance assertion');
  const verified = !missing.length && !unasserted.length;
  const status = f.blocked ? 'Blocked' : missing.length ? 'Missing Evidence' : !verified ? 'Implemented' : f.boundary ? 'Simplified With A Boundary' : 'Behaviorally Verified';
  return { ...f, missing: [...missing, ...unasserted], status };
});

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const lines = [];
lines.push(`# ${data.title}`, '');
lines.push(`Generated by \`node tools/student-matrix.mjs --write\` from \`docs/verification/student-matrix.json\`, as of ${data.asOf}. Each row's status is worked out by the tool from its evidence, not written in the data: every command it names registered in the engine, every test it cites in its file by title, and every acceptance assertion's test found. Verified is not the same as real-world accurate: the Basis column, the boundary and Remaining Limitation say where SLATE follows a source, simplifies, designs its own or is unsure.`, '');
const ok = (r) => r.status === 'Behaviorally Verified' || r.status === 'Simplified With A Boundary';
for (const area of ['School', 'Banking', 'Papers']) {
  const a = rows.filter((r) => r.area === area);
  lines.push(`- **${area}:** ${a.filter(ok).length} of ${a.length} verified (${a.filter((r) => r.status === 'Simplified With A Boundary').length} with a boundary), ${a.filter((r) => r.status === 'Implemented').length} implemented only, ${a.filter((r) => r.status === 'Blocked').length} blocked.`);
}
lines.push('', '## Statuses', '');
for (const [k, v] of Object.entries(data.statusKey ?? {})) lines.push(`- **${k}**: ${v}`);
lines.push('', '## Basis', '');
for (const [k, v] of Object.entries(data.basisKey)) lines.push(`- **${k}**: ${v}`);
for (const area of ['School', 'Banking', 'Papers']) {
  lines.push('', `## ${area}`, '');
  lines.push('| Player Goal | Entry | Prerequisites | Choices | Steps | Costs | States | Failure And Refusal | Recovery | State Read And Changed | Downstream | Notifications | Save And Load | Source | Basis | Evidence | Acceptance: Outcome, Reader | Status | Remaining Limitation |');
  lines.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|');
  for (const r of rows.filter((x) => x.area === area)) {
    const ev = r.tests.map((t) => `\`${t.file.replace('tests/', '')}\`${t.title ? `: “${t.title}”` : ''}`).join('; ') + (r.commands.length ? `. Commands: ${r.commands.map((c) => `\`${c}\``).join(', ')}` : '');
    const accept = (r.acceptance ?? []).map((a) => `${a.outcome}; read by ${a.reader} (\`${a.file.replace('tests/', '')}\`)`).join(' / ');
    lines.push(`| ${esc(r.goal)} | ${esc(r.entry)} | ${esc(r.prereqs)} | ${esc(r.choices)} | ${esc(r.steps)} | ${esc(r.costs)} | ${esc(r.states)} | ${esc(r.failure)} | ${esc(r.recovery)} | ${esc(r.stateRW)} | ${esc(r.consumers)} | ${esc(r.notices)} | ${esc(r.saveLoad)} | ${esc(r.source)} | ${esc(r.basis)} | ${esc(ev)} | ${esc(accept)} | ${r.status}${r.missing.length ? `: ${esc(r.missing.join(', '))}` : ''}${r.boundary ? `. Boundary: ${esc(r.boundary)}` : ''} | ${esc(r.limitations)} |`);
  }
}
const gaps = rows.filter((r) => r.initialGap);
lines.push('', '## Gaps Found At The Start, And What Became Of Them', '');
lines.push('From the audits checked in beside this file (`school-journey-audit.json`, `papers-bank-audit.json`) and the research. Each row whose goal had a gap:', '');
for (const r of gaps) lines.push(`- **${r.goal}.** ${r.initialGap} ${r.resolution ?? ''}`);
const changed = rows.filter((r) => r.before !== undefined);
lines.push('', '## Before And After', '');
lines.push('Each row whose limitation this pass changed, its old text and its new:', '');
for (const r of changed) lines.push(`- **${r.goal}.** Before: ${r.before} After: ${r.limitations}`);
lines.push('', '## Deferred, Not Counted', '');
lines.push(`The ${data.deferred.length} items deferred by the owner stay deferred and outside the counts above (\`docs/verification/COVERAGE-GAPS.md\`):`, '');
for (const d of data.deferred) lines.push(`- \`${d}\``);
lines.push('');
const text = lines.join('\n');

const missing = rows.filter((r) => r.missing.length);
if (process.argv.includes('--write')) { writeFileSync(out, text); console.log(`Wrote ${out}: ${rows.length - missing.length} of ${rows.length} verified.`); }
if (process.argv.includes('--check')) {
  if (missing.length) { for (const r of missing) console.error(`${r.id}: ${r.missing.join(', ')}`); process.exit(1); }
  if (!existsSync(out) || readFileSync(out, 'utf8') !== text) { console.error(`${out} is out of date: node tools/student-matrix.mjs --write`); process.exit(1); }
  console.log(`${out} matches: ${rows.length} of ${rows.length} verified.`);
}
for (const r of missing) console.log(`MISSING ${r.id}: ${r.missing.join(', ')}`);
