/**
 * The reference catalog's coverage inventory (from 2026-10-23, the owner's brief 25, Part 5: "Create a transparent
 * major-company coverage inventory ... Report: Catalog pages inspected. Titles discovered. Titles imported. Duplicates
 * removed. Unresolved records. Unverified fields."; `docs/verification/career-world-2026-10-23/criteria.md`, Module 2,
 * C6): every figure worked out from `src/engine/content/catalog.ts`, its pages read and its records, and the register's
 * sources, written to docs/verification/career-world-2026-10-23/CATALOG.md with each production field by field.
 *
 *   npx vite-node tools/catalog.mjs           prints the totals
 *   npx vite-node tools/catalog.mjs --write   writes CATALOG.md
 *
 * tests/career-catalog.test.ts fails when the page isn't what this writes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { CATALOG, COMPANIES, PAGES_READ, companyName } from '../src/engine/content/catalog.ts';

export const PAGE = 'docs/verification/career-world-2026-10-23/CATALOG.md';
const SOURCES = JSON.parse(readFileSync('docs/verification/career-world-2026-10-23/sources.json', 'utf8')).sources;
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** Every field of a production, by name, flattened: the scalar fields, each season's and each credit's character. */
export function fieldsOf(p) {
  const out = [['genres', p.genres], ['status', p.status], ['languages', p.languages], ['runtime', p.runtime], ['filming', p.filming], ['release', p.release]];
  for (const s of p.seasons) out.push([`season ${s.n} episodes`, s.episodes], [`season ${s.n} premiere`, s.premiere], [`season ${s.n} schedule`, s.schedule]);
  for (const c of p.cast) out.push([`${c.performer}'s character`, c.character]);
  return out;
}

/** The inventory's figures, from the pages read and the records. */
export function inventory() {
  const titles = CATALOG.map((p) => p.title);
  const discovered = [...new Set(PAGES_READ.flatMap((r) => r.titles))];
  const imported = discovered.filter((t) => titles.includes(t));
  const notImported = PAGES_READ.flatMap((r) => Object.entries(r.notImported ?? {}).map(([title, why]) => ({ title, why, source: r.source })));
  // A title named on more than one page, merged into one record.
  const duplicates = imported.map((t) => ({ title: t, pages: PAGES_READ.filter((r) => r.titles.includes(t)).map((r) => r.source) })).filter((d) => d.pages.length > 1);
  const unresolved = PAGES_READ.filter((r) => r.result === 'unreadable').map((r) => ({ source: r.source, why: SOURCES.find((s) => s.id === r.source)?.attempts?.at(-1)?.result ?? '' }));
  const fields = CATALOG.flatMap((p) => fieldsOf(p).map(([name, f]) => ({ title: p.title, name, f })));
  const unverified = fields.filter((x) => x.f.kind === 'unknown' || x.f.kind === 'assumption');
  return { pages: PAGES_READ.length, discovered, imported, notImported, duplicates, unresolved, fields: fields.length, unverified };
}

const scope = (s) => (s.kind === 'season' ? `season ${s.n}` : s.kind);
const say = (f) => (f.kind === 'read' ? `${Array.isArray(f.value) ? f.value.join(', ') : f.value} (${f.source})` : f.kind === 'conflict' ? `${f.value} (${f.source}; against ${f.against.value}, ${f.against.source}: ${f.why})` : f.kind === 'assumption' ? `${f.value} (the game’s assumption: ${f.why})` : `Unknown: ${f.why}`);

export function render() {
  const inv = inventory();
  const L = [
    '# The Reference Catalog',
    '',
    'Generated by `npx vite-node tools/catalog.mjs --write` from `src/engine/content/catalog.ts` and `sources.json`; `tests/career-catalog.test.ts` fails when this page is behind them. Brief 25, Parts 3 and 5; `criteria.md`, Module 2.',
    '',
    'What official pages said on 2026-10-23, the day this build read them, field by field. It isn’t every current production: it’s the four series the brief names and the one studio slate this build read.',
    '',
    '## The Inventory',
    '',
    `- **Pages inspected:** ${inv.pages} (${PAGES_READ.map((r) => r.source).join(', ')}).`,
    `- **Titles discovered:** ${inv.discovered.length}.`,
    `- **Titles imported:** ${inv.imported.length}.`,
    `- **Duplicates merged:** ${inv.duplicates.length}: ${inv.duplicates.map((d) => `${d.title} (${d.pages.join(', ')})`).join('; ')}.`,
    `- **Named and not imported:** ${inv.notImported.length}: ${inv.notImported.map((x) => `${x.title} (${x.source}): ${x.why}`).join(' ')}`,
    `- **Unresolved records:** ${inv.unresolved.length}: ${inv.unresolved.map((u) => `${u.source}, ${u.why}`).join('; ')}.`,
    `- **Unverified fields:** ${inv.unverified.length} of ${inv.fields}, each unknown or the game’s assumption, listed under its production.`,
    '',
    '## Companies',
    '',
    '| Company | Roles, by production |',
    '| --- | --- |',
  ];
  for (const c of COMPANIES) {
    const roles = CATALOG.flatMap((p) => p.companies.filter((x) => x.company === c.id).map((x) => `${x.role} of ${p.title} (${x.source})`));
    L.push(`| ${c.name} | ${cell(roles.join('; '))} |`);
  }
  for (const p of CATALOG) {
    L.push('', `## ${p.title}`, '', `A ${p.format}, \`${p.id}\`. Sources: ${p.sources.join(', ')}.`, '');
    L.push('| Field | Value |', '| --- | --- |');
    for (const [name, f] of fieldsOf(p)) if (!name.endsWith('character')) L.push(`| ${cell(name)} | ${cell(say(f))} |`);
    if (p.companies.length) L.push(`| companies | ${cell(p.companies.map((c) => `${companyName(c.company)}, ${c.role} (${c.source})`).join('; '))} |`);
    if (p.people.length) L.push(`| people | ${cell(p.people.map((x) => `${x.name}, ${x.role}, ${scope(x.scope)} (${x.source})`).join('; '))} |`);
    if (p.ratings.length) L.push(`| ratings | ${cell(p.ratings.map((r) => `${r.rating} in ${r.territory} (${r.source})`).join('; '))} |`);
    if (p.cast.length) L.push(`| cast | ${cell(p.cast.map((c) => `${c.performer}: ${c.character.kind === 'read' ? c.character.value : 'character unknown'}, ${scope(c.scope)} (${c.source})`).join('; '))} |`);
  }
  L.push('');
  return { text: L.join('\n'), inv };
}

// Run as a tool, not loaded by the test: vite-node takes the file's own name out of process.argv, so it's told by VITEST.
if (!process.env.VITEST) {
  const { text, inv } = render();
  if (process.argv.includes('--write')) writeFileSync(PAGE, text);
  console.log(`${inv.pages} pages, ${inv.discovered.length} titles discovered, ${inv.imported.length} imported, ${inv.duplicates.length} merged, ${inv.unresolved.length} unresolved, ${inv.unverified.length} of ${inv.fields} fields unverified${process.argv.includes('--write') ? `; wrote ${PAGE}` : ''}`);
}
