#!/usr/bin/env node
/**
 * The engine's inventory, read from the code.
 *
 * Every command kind registered with `onCommand`, every scheduled kind with
 * `onSchedule`, everything time does as it passes with `onPassage`, every
 * event emitted with `emit` and every listener with `onEvent`, grouped by
 * system prefix, with the file that owns each. Also the scene definitions and
 * the routes the shell offers.
 *
 *   node tools/inventory.mjs              summary counts
 *   node tools/inventory.mjs --markdown   the appendix docs/COVERAGE-MATRIX.md carries
 *   node tools/inventory.mjs --check      fail if the doc's appendix is behind the code
 *
 * The check is what keeps the coverage matrix honest: a command added to the
 * engine without a line in the matrix fails the gate.
 */

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';

const BEGIN = '<!-- inventory:begin -->';
const END = '<!-- inventory:end -->';

// Paths are repo-relative with forward slashes, the way every other tool here
// works and the way the matrix itself spells them. Deriving a base directory
// from `import.meta.url` gave `/C:/...` on Windows, which `join` then turned
// into a path with a drive letter in the middle of it.
function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = `${dir}/${name}`;
    if (statSync(full).isDirectory()) walk(full, out);
    else if (full.endsWith('.ts') || full.endsWith('.tsx')) out.push(full);
  }
  return out;
}

function collect() {
  const commands = new Map();
  const schedules = new Map();
  const passages = new Map();
  const events = new Map();
  const listeners = new Map();
  const scenes = new Map();

  // A kind is often a named constant rather than a literal, because the
  // interface has to name it too: `onSchedule(LOT_OVERHEAD_KIND)`, not
  // `onSchedule('lot.overhead')`. Reading only for literals made those
  // invisible, so this counted the game's surface as smaller than it was and
  // said so with a straight face. tests/cohesion.test.ts already resolves
  // constants for exactly this reason; this does now too.
  const named = new Map();
  const files = walk('src/engine').sort();
  for (const file of files) {
    for (const m of readFileSync(file, 'utf8').matchAll(/const ([A-Z][A-Z0-9_]*) = '([a-z0-9_]+\.[a-z0-9_]+)'/g)) {
      named.set(m[1], m[2]);
    }
  }
  const kindOf = (token) => (token.startsWith("'") ? token.slice(1, -1) : named.get(token));

  for (const file of files) {
    const text = readFileSync(file, 'utf8');
    const rel = file;
    const add = (map, re, group = 1) => {
      for (const m of text.matchAll(re)) {
        const kind = kindOf(m[group]);
        if (kind && !map.has(kind)) map.set(kind, rel);
      }
    };
    add(commands, /onCommand(?:<[^(]*?>)?\(\s*('[a-z0-9_.]+'|[A-Z][A-Z0-9_]*)/gs);
    add(schedules, /onSchedule\(\s*('[a-z0-9_.]+'|[A-Z][A-Z0-9_]*)/g);
    add(passages, /onPassage\(\s*('[a-z0-9_.]+'|[A-Z][A-Z0-9_]*)/g);
    add(events, /\.emit\(\s*('[a-z0-9_.]+'|[A-Z][A-Z0-9_]*)/g);
    add(listeners, /onEvent\(\s*('[a-z0-9_.]+'|[A-Z][A-Z0-9_]*)/g);
    if (rel.startsWith('src/engine/scenes/')) add(scenes, /defineScene\(\{\s*id:\s*('[a-z0-9_.]+')/g);
  }
  const routes = new Set();
  for (const m of readFileSync('src/ui/shell/destinations.ts', 'utf8').matchAll(/route:\s*'(\/[a-z/-]*)'/g)) {
    routes.add(m[1]);
  }
  return { commands, schedules, passages, events, listeners, scenes, routes: [...routes].sort() };
}

function grouped(map) {
  const by = new Map();
  for (const [kind, file] of map) {
    const prefix = kind.split('.')[0];
    if (!by.has(prefix)) by.set(prefix, []);
    by.get(prefix).push({ kind, file });
  }
  return [...by.entries()].sort(([a], [b]) => a.localeCompare(b));
}

function markdown(inv) {
  const lines = [];
  lines.push(`Generated by \`node tools/inventory.mjs --markdown\`. ${inv.commands.size} commands, ${inv.schedules.size} scheduled kinds, ${inv.passages.size} passage reactors, ${inv.events.size} events emitted, ${inv.listeners.size} event listeners, ${inv.scenes.size} scenes, ${inv.routes.length} routes.`);
  lines.push('');
  const table = (title, map) => {
    lines.push(`### ${title}`);
    lines.push('');
    lines.push('| System | Kinds | Owner |');
    lines.push('| --- | --- | --- |');
    for (const [prefix, items] of grouped(map)) {
      const files = [...new Set(items.map((i) => i.file))].map((f) => `\`${f}\``).join(', ');
      lines.push(`| ${prefix} | ${items.map((i) => `\`${i.kind}\``).sort().join(' ')} | ${files} |`);
    }
    lines.push('');
  };
  table('Commands', inv.commands);
  table('Scheduled kinds', inv.schedules);
  table('Passage reactors', inv.passages);
  table('Events emitted', inv.events);
  table('Event listeners', inv.listeners);
  lines.push('### Scenes');
  lines.push('');
  lines.push('| Scene | Owner |');
  lines.push('| --- | --- |');
  for (const [id, file] of [...inv.scenes.entries()].sort()) lines.push(`| \`${id}\` | \`${file}\` |`);
  lines.push('');
  lines.push('### Routes');
  lines.push('');
  lines.push(inv.routes.map((r) => `\`${r}\``).join(' · '));
  return lines.join('\n');
}

const inv = collect();
const mode = process.argv[2] ?? '';
const docPath = 'docs/COVERAGE-MATRIX.md';

if (mode === '--markdown') {
  process.stdout.write(`${markdown(inv)}\n`);
} else if (mode === '--write') {
  const doc = readFileSync(docPath, 'utf8');
  const start = doc.indexOf(BEGIN);
  const end = doc.indexOf(END);
  if (start < 0 || end < 0) { console.error(`No ${BEGIN} … ${END} block in ${docPath}`); process.exit(1); }
  writeFileSync(docPath, `${doc.slice(0, start + BEGIN.length)}\n${markdown(inv)}\n${doc.slice(end)}`);
  console.log(`Wrote the inventory into ${docPath}.`);
} else if (mode === '--check') {
  const doc = readFileSync(docPath, 'utf8');
  const start = doc.indexOf(BEGIN);
  const end = doc.indexOf(END);
  if (start < 0 || end < 0) { console.error(`No inventory block in ${docPath}`); process.exit(1); }
  // Compared as content, not as bytes: a checkout with CRLF endings is still
  // the same inventory, and comparing the terminators made this fail on Windows
  // no matter what the block said.
  const flat = (text) => text.replace(/\r\n/g, '\n').trim();
  const current = flat(doc.slice(start + BEGIN.length, end));
  const expected = flat(markdown(inv));
  if (current !== expected) {
    console.error('docs/COVERAGE-MATRIX.md is behind the code. Run: node tools/inventory.mjs --write');
    process.exit(1);
  }
  // Every command, scene and route must also be named somewhere in the matrix body, not only the appendix.
  const body = doc.slice(0, start);
  const missing = [];
  for (const kind of inv.commands.keys()) if (!body.includes(`\`${kind}\``) && !body.includes(`\`${kind.split('.')[0]}.*\``)) missing.push(kind);
  for (const id of inv.scenes.keys()) if (!body.includes(`\`${id}\``)) missing.push(id);
  for (const route of inv.routes) if (!body.includes(`\`${route}\``)) missing.push(route);
  if (missing.length > 0) {
    console.error(`Named in the code but not in the matrix body: ${missing.join(', ')}`);
    process.exit(1);
  }
  console.log(`Inventory matches the code: ${inv.commands.size} commands, ${inv.schedules.size} scheduled kinds, ${inv.passages.size} passage reactors, ${inv.events.size} events, ${inv.listeners.size} listeners, ${inv.scenes.size} scenes, ${inv.routes.length} routes.`);
} else {
  console.log(`commands ${inv.commands.size} · scheduled kinds ${inv.schedules.size} · passage reactors ${inv.passages.size} · events emitted ${inv.events.size} · event listeners ${inv.listeners.size} · scenes ${inv.scenes.size} · routes ${inv.routes.length}`);
  for (const [prefix, items] of grouped(inv.commands)) console.log(`  ${prefix}: ${items.length}`);
}
