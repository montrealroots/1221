/**
 * Where the game lets an actor work on screen, country by country (from 2026-10-23, the owner's brief 25, Part 9:
 * "Maintain a country coverage matrix"; `docs/verification/career-world-2026-10-23/criteria.md`, W1): every country of
 * the gazetteer, in the state `src/engine/content/jurisdictions.ts` gives it, with its routes, each route's conditions
 * (the source's words beside each verified one, the game's assumptions said as such), the sources located for it and
 * what isn't in the game yet. Written to docs/verification/career-world-2026-10-23/COUNTRIES.md.
 *
 *   npx vite-node tools/countries.mjs           prints the totals
 *   npx vite-node tools/countries.mjs --write   writes COUNTRIES.md
 *
 * tests/career-world-countries.test.ts fails when the page isn't what this writes, so the gate holds the page to the
 * registry without a check of its own.
 */
import { writeFileSync } from 'node:fs';
import { COUNTRIES } from '../src/engine/content/geography.ts';
import { JURISDICTIONS, gapWords, jurisdictionOf } from '../src/engine/content/jurisdictions.ts';

export const PAGE = 'docs/verification/career-world-2026-10-23/COUNTRIES.md';

const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** The page, as the registry has it. */
export function render() {
  const all = COUNTRIES.all().filter((c) => c.id !== 'us').sort((a, b) => a.name.localeCompare(b.name));
  const by = { verified: [], partial: [], unsupported: [] };
  for (const c of all) by[jurisdictionOf(c.id, c.name).research].push(c);
  const out = [
    '# Where The Game Lets You Work On Screen',
    '',
    'Generated by `npx vite-node tools/countries.mjs --write` from `src/engine/content/jurisdictions.ts`; `tests/career-world-countries.test.ts` fails when this page is behind it. Brief 25, Part 9; `criteria.md`, W1 and W2.',
    '',
    `The gazetteer's ${COUNTRIES.all().length} countries: the United States, ${by.verified.length} verified, ${by.partial.length} partly researched and ${by.unsupported.length} unsupported.`,
    '',
    '- **The United States** is the package brief 19 built (`systems/permission.ts`, `usWorkAuthorized`: citizenship, a green card, OPT), not a route here.',
    '- **Verified**: a route to permission for screen work, its conditions read from the government’s own page on a recorded date. The game applies it.',
    '- **Partly researched**: sources located, rules not extracted. A role there can’t be accepted, and the refusal says why.',
    '- **Unsupported**: nothing researched. Missing rules are never permission: a role there can’t be accepted, and the refusal says why.',
    '',
    '## Verified',
    '',
  ];
  for (const c of by.verified) {
    const j = JURISDICTIONS[c.id];
    out.push(`### ${j.name} (${j.iso})`, '', `Sources: ${j.sources.join(', ')}. ${gapWords(j)}`, '');
    for (const r of j.routes) {
      const who = r.for.kind === 'non-citizens' ? 'anyone without the country’s citizenship' : `citizens of ${r.for.iso} with that country’s passport`;
      out.push(`#### ${r.name}`, '', `For ${who}; ${r.how === 'apply-ahead' ? 'applied for ahead, with the production’s support' : 'granted on arrival'}. Source ${r.source.id}, ${r.source.url}, read ${r.source.read}${r.source.updated ? `, the page last updated ${r.source.updated}` : ''}.`, '');
      out.push('| Condition | Basis | What the game says | The source’s words |', '| --- | --- | --- | --- |');
      for (const k of r.conditions) out.push(`| ${k.id} | ${k.basis} | ${cell(k.words)} | ${k.quote ? cell(`“${k.quote}”`) : 'None: the game’s assumption'} |`);
      out.push('');
    }
  }
  out.push('## Partly Researched', '', '| Country | ISO | Sources | Not in the game yet |', '| --- | --- | --- | --- |');
  for (const c of by.partial) { const j = JURISDICTIONS[c.id]; out.push(`| ${j.name} | ${j.iso} | ${j.sources.join(', ')} | ${cell(j.gaps.join('; '))} |`); }
  out.push('', '## Unsupported', '', `${by.unsupported.length} countries, none of their rules for working there in the game:`, '', '| Country | ISO |', '| --- | --- |');
  for (const c of by.unsupported) out.push(`| ${c.name} | ${c.iso2 ?? ''} |`);
  out.push('');
  return { text: out.join('\n'), counts: { verified: by.verified.length, partial: by.partial.length, unsupported: by.unsupported.length } };
}

// Run as a tool, not loaded by the test: vite-node takes the file's own name out of process.argv, so it's told by VITEST.
if (!process.env.VITEST) {
  const { text, counts } = render();
  if (process.argv.includes('--write')) writeFileSync(PAGE, text);
  console.log(`${counts.verified} verified, ${counts.partial} partly researched, ${counts.unsupported} unsupported${process.argv.includes('--write') ? `; wrote ${PAGE}` : ''}`);
}
