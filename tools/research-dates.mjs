/** Applies `edit` to every field `paths` names in `data`, and returns the changes made. */
export function editFields(data, paths, edit) {
  const changes = [];
  for (const path of paths) {
    const [first, ...rest] = path.split('.');
    const keys = first === '*' ? Object.keys(data) : [first];
    for (const key of keys) {
      let holder = data[key];
      const field = rest.at(-1);
      for (const step of rest.slice(0, -1)) holder = holder?.[step];
      if (!holder || typeof holder[field] !== 'string') continue;
      const after = edit(holder[field]);
      if (after !== holder[field]) { changes.push({ key, field, before: holder[field], after }); holder[field] = after; }
    }
  }
  return changes;
}

/** Each `export const NAME … = JSON.parse("…");` in a generated file: its name, the literal's span and its data. */
function parsedExports(source) {
  const out = [];
  for (const m of source.matchAll(/export const (\w+)\b[^=]*= JSON\.parse\(("(?:[^"\\]|\\.)*")\);/g)) {
    const at = m.index + m[0].indexOf('JSON.parse(') + 'JSON.parse('.length;
    out.push({ name: m[1], start: at, end: at + m[2].length, data: JSON.parse(JSON.parse(m[2])), literal: m[2] });
  }
  return out;
}

function main() {
  const write = process.argv.includes('--write');
  let total = 0;
  for (const [file, exports] of Object.entries(GENERATED)) {
    let source = readFileSync(file, 'utf8');
    const found = parsedExports(source);
    for (const one of found.reverse()) {
      const paths = exports[one.name];
      if (!paths) continue;
      // The generator's form: the data stringified, inside JSON.parse. A file not in that form isn't rewritten.
      if (JSON.stringify(JSON.stringify(one.data)) !== one.literal) { console.error(`${file} ${one.name}: not in the generator's form, left as it is`); process.exitCode = 2; continue; }
      const changes = editFields(one.data, paths, (t) => noSpaceBefore(gameAccess(gameDates(t))));
      for (const [f, name, key, field, was, now] of BY_HAND) {
        if (f !== file || name !== one.name) continue;
        const text = one.data[key]?.[field];
        const n = typeof text === 'string' ? text.split(was).length - 1 : 0;
        if (n === 1) { const after = text.replace(was, now); changes.push({ key, field, before: text, after }); one.data[key][field] = after; }
        else if (!(typeof text === 'string' && text.includes(now))) { console.error(`${file} ${name}.${key}.${field}: "${was}" is in it ${n} times, not once`); process.exitCode = 2; }
      }
      for (const c of changes) console.log(`${file} ${one.name}.${c.key}.${c.field}\n  - ${c.before}\n  + ${c.after}`);
      total += changes.length;
      if (write && changes.length) source = source.slice(0, one.start) + JSON.stringify(JSON.stringify(one.data)) + source.slice(one.end);
    }
    if (write) writeFileSync(file, source);
  }
  console.log(`${total} fields ${write ? 'rewritten' : 'would be rewritten'}`);
  if (!write && total) process.exitCode = 1;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
