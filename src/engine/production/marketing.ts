/**
 * SLATE — producer-side marketing before a picture is sold.
 *
 * Distributor P&A remains part of the sale waterfall. This is different money:
 * the producer deciding how much awareness to build before the buyer/release
 * machinery takes over. The committed total is stored; awareness is derived.
 */

import type { Simulation } from '../core/simulation';
import type { Money } from '../core/money';
import type { Id } from '../domain/model';
import type { MarketingStrategy, Project } from '../domain/company';
import { cashAccountFor } from '../world/company';

export interface MarketingPlan {
  id: MarketingStrategy;
  label: string;
  efficiency: number;
  recommendedShare: number;
  description: string;
}

export const MARKETING_STRATEGIES: readonly MarketingPlan[] = [
  {
    id: 'minimal',
    label: 'Minimal',
    efficiency: 0.72,
    recommendedShare: 0.01,
    description: 'Press materials, listings and enough paid reach for the release to exist in public.',
  },
  {
    id: 'targeted',
    label: 'Targeted',
    efficiency: 1,
    recommendedShare: 0.05,
    description: 'Spend concentrated on the audiences most likely to care about this particular title.',
  },
  {
    id: 'wide',
    label: 'Wide',
    efficiency: 1.12,
    recommendedShare: 0.12,
    description: 'A broad campaign buying awareness before opening rather than waiting for word of mouth.',
  },
  {
    id: 'event',
    label: 'Event',
    efficiency: 1.22,
    recommendedShare: 0.2,
    description: 'A saturation campaign meant to make opening itself feel like the event.',
  },
];

export const MARKETING_BY_ID: Readonly<Record<MarketingStrategy, MarketingPlan>> =
  Object.fromEntries(MARKETING_STRATEGIES.map((one) => [one.id, one])) as Record<MarketingStrategy, MarketingPlan>;

export const MAX_PRODUCER_MARKETING_SHARE = 0.5;

export interface CommitMarketing {
  projectId: Id;
  strategy: MarketingStrategy;
  spendCents: Money;
}

export interface MarketingResult {
  ok: boolean;
  error?: string;
  awareness?: number;
  chargedCents?: Money;
}

/**
 * Awareness generated by the campaign, 0-100.
 *
 * Spend has diminishing returns. A campaign at twenty percent of the negative
 * is already buying most of the available awareness, so doubling it is not a
 * second opening weekend. Strategy changes efficiency, not the existence of a
 * magic audience.
 */
export function marketingAwareness(project: Project): number | undefined {
  const campaign = project.marketing;
  const negative = project.budgetCents ?? campaign?.spendCents ?? 0;
  if (!campaign || negative <= 0) return undefined;
  const share = Math.max(0, campaign.spendCents / negative);
  const plan = MARKETING_BY_ID[campaign.strategy];
  const reach = Math.min(1, Math.pow(share / 0.2, 0.55));
  return Math.max(0, Math.min(100, Math.round(12 + 76 * reach * plan.efficiency)));
}

/** A campaign can be revised upward, never unspent. */
export function commitMarketing(sim: Simulation, spec: CommitMarketing): MarketingResult {
  const project = sim.universe.projects[spec.projectId];
  if (!project) return { ok: false, error: 'There is no such project.' };
  if (project.dealId) return { ok: false, error: project.title + ' has already been sold.' };
  if (project.stage !== 'post' && project.stage !== 'delivered') {
    return { ok: false, error: 'Marketing opens in post-production, once there is a picture to sell.' };
  }
  const plan = MARKETING_BY_ID[spec.strategy];
  if (!plan) return { ok: false, error: 'That is not a marketing strategy.' };

  const total = Math.round(spec.spendCents);
  if (!Number.isFinite(total) || total < 0) return { ok: false, error: 'That is not a marketing budget.' };
  const negative = project.budgetCents ?? 0;
  if (negative <= 0) return { ok: false, error: 'The picture has no production budget to size a campaign against.' };
  const most = Math.round(negative * MAX_PRODUCER_MARKETING_SHARE);
  if (total > most) {
    return {
      ok: false,
      error: 'Producer marketing is capped at half the production budget in this build.',
    };
  }

  const before = project.marketing?.spendCents ?? 0;
  if (total < before) {
    return { ok: false, error: 'Money already committed to a campaign cannot be unspent.' };
  }
  const extra = total - before;
  if (extra > 0) {
    const account = cashAccountFor(sim.universe, project.companyId);
    if (!account) return { ok: false, error: 'The company has no production account to pay marketing from.' };
    sim.expense(
      account.id,
      extra,
      project.title + ': Producer Marketing',
      'business',
      { refType: 'project', refId: project.id },
    );
  }

  project.marketing = {
    strategy: plan.id,
    spendCents: total,
    startedAt: project.marketing?.startedAt ?? sim.now,
    updatedAt: sim.now,
  };
  const awareness = marketingAwareness(project) ?? 0;

  sim.notify({
    category: 'business',
    title: project.title + ': Campaign Set',
    body: plan.label + ' marketing now has ' + Math.round(total / 100).toLocaleString('en-US')
      + ' committed to it. Awareness is ' + awareness + '/100.',
    importance: 45,
    refType: 'project',
    refId: project.id,
  });

  return { ok: true, awareness, chargedCents: extra };
}

export function registerMarketing(sim: Simulation): void {
  sim.onCommand<CommitMarketing, MarketingResult>(
    'production.marketing.commit',
    (payload, { sim: s }) => commitMarketing(s, payload),
  );
}
