/**
 * SLATE — the connected attributes' itemized matrix (from 2026-10-09), built
 * from the tables themselves so it can't drift from them:
 * `docs/ATTRIBUTES-MATRIX.md` is this function's output, and
 * `tests/attributes-matrix.test.ts` fails when the two differ.
 *
 * One row per ability, technique, interest, genre, task profile, profile
 * section and destination, each with where its state is saved, the action
 * that reaches it, the calculation that reads it, where its result shows, what
 * reads it downstream, and the test that holds it.
 */

import { ABILITY_DEFS, TECHNIQUES, TECHNIQUE_LABEL, type AbilityId } from './abilities';
import { EXERCISES, exerciseFor } from './practice';
import { INTEREST_DEFS } from './engagement';
import { GENRE_DEFS } from './genres';
import { ALL_INTERESTS, FILM_GENRES } from './interests';
import { TASK_PROFILES, TEMPLATE_TASK, DIMENSION_LABEL, type Dimension } from './tasks';

const SAVED: Readonly<Partial<Record<AbilityId, string>>> = { emotionalDepth: '`craft.emotion`', memory: '`craft.memorization`', vocal: '`craft.voice`', physical: '`craft.movement`', stamina: '`wellbeing.fitness`' };
const ORDINARY: Readonly<Partial<Record<AbilityId, string>>> = {
  emotionalDepth: 'classes (Acting I, Play), nights', presence: 'nights, a remarkable night', listening: 'classes, partner rehearsals, nights',
  imagination: 'classes, coursework interpretation, reading plays', focus: 'classes, coursework familiarity', memory: 'classes, coursework lines, learning a part, the blocking book',
  adaptability: 'classes (Play), a revision, a director’s note worked', composure: 'every performance’s nerves', vocal: 'voice classes', physical: 'movement classes',
  discipline: 'a call answered, a day practiced', stamina: 'a workout, a run',
};

const readers = (id: AbilityId) => Object.values(TASK_PROFILES).flatMap((t) => (Object.entries(t.dims) as [Dimension, NonNullable<(typeof t.dims)[Dimension]>][]).filter(([, s]) => s.inputs.some((i) => 'ability' in i && i.ability === id)).map(([d]) => `${t.label}: ${DIMENSION_LABEL[d]}`));
const row = (cells: string[]) => `| ${cells.map((c) => c.replace(/\|/g, '/')).join(' | ')} |`;
const HEAD = row(['Item', 'Saved State', 'Reachable Action', 'Calculation', 'Visible Result', 'Downstream Consumer', 'Test Evidence']) + '\n| --- | --- | --- | --- | --- | --- | --- |';

export function attributesMatrix(): string {
  const out: string[] = [];
  out.push('# The Connected Attributes, Item By Item', '', 'Generated by `attributesMatrix()` in `src/engine/content/attributes-matrix.ts`; `tests/attributes-matrix.test.ts` fails when this file and the tables differ. Written 2026-10-09.', '');

  out.push(`## Abilities: ${ABILITY_DEFS.length} of ${ABILITY_DEFS.length}`, '', HEAD);
  for (const d of ABILITY_DEFS) {
    const e = exerciseFor(d.id);
    out.push(row([d.label, SAVED[d.id] ?? `\`attrs.${d.id}\``, `${ORDINARY[d.id] ?? ''}${e ? `; \`practice.exercise\` ${e.label}` : ''}`, '`develop` (attributes.ts); read by `evaluate` as level / full', 'Player Profile, Attributes And Craft; `look.ability`', readers(d.id).join('; ') || 'none', '`tests/evaluation.test.ts`, `tests/development.test.ts`']));
  }

  out.push('', `## Techniques: ${TECHNIQUES.length} of ${TECHNIQUES.length}`, '', HEAD);
  for (const t of TECHNIQUES) {
    const e = exerciseFor(t);
    const work = Object.entries(TEMPLATE_TASK).length;
    out.push(row([TECHNIQUE_LABEL[t], `\`craft.${t}\``, `classes; coursework steps that train it; ${e ? `\`practice.exercise\` ${e.label}` : 'no exercise'}`, '`develop`; read by `evaluate` as level / 90 where the work reads it', 'Player Profile, Techniques; `look.skill`', `the ${work} coursework templates and every play that reads it; casting (\`readOf\`)`, '`tests/development.test.ts` (its exercise), `tests/evaluation.test.ts`']));
  }

  out.push('', `## Interests: ${ALL_INTERESTS.filter((i) => INTEREST_DEFS[i.id]).length} of ${ALL_INTERESTS.length}`, '', HEAD);
  for (const i of ALL_INTERESTS) {
    const d = INTEREST_DEFS[i.id];
    if (!d) { out.push(row([i.label, 'none', 'none', 'none', 'none', 'none', 'none'])); continue; }
    const target = (ABILITY_DEFS.find((a) => a.id === d.develops)?.label) ?? TECHNIQUE_LABEL[d.develops as (typeof TECHNIQUES)[number]];
    out.push(row([i.label, '`engagement.byInterest`', '`interest.pursue`', `rest: ${d.recovery ?? 'none (a trade studied)'}, less satiation; grows ${target}`, 'Player Profile, Interests; `look.interest`', `${d.recovery ? 'stress and morale; ' : ''}${target} (the evaluation)`, '`tests/engagement.test.ts` (every interest)']));
  }

  out.push('', `## Genres: ${FILM_GENRES.filter((g) => GENRE_DEFS[g.id]).length} of ${FILM_GENRES.length}`, '', HEAD);
  for (const g of FILM_GENRES) {
    const d = GENRE_DEFS[g.id];
    if (!d) { out.push(row([g.label, 'none', 'none', 'none', 'none', 'none', 'none'])); continue; }
    out.push(row([g.label, '`engagement.byGenre`', '`genre.study`, `practice.self_tape`, a night of a play of the kind', `families ${d.families.join(', ')} lean the dimensions; \`genreSpeed\``, 'Player Profile, Genres; `look.genre`; `look.work`', 'preparation speed (coursework, a part’s lines); a self-tape’s “knowing the genre”', '`tests/engagement.test.ts` (every genre)']));
  }

  out.push('', `## Task Profiles: ${Object.keys(TASK_PROFILES).length} of ${Object.keys(TASK_PROFILES).length}`, '', row(['Profile', 'Dimensions', 'Judged In', 'Consumer', 'Test Evidence']), '| --- | --- | --- | --- | --- |');
  for (const t of Object.values(TASK_PROFILES)) {
    const where = t.id === 'performance' ? 'a night, a dress (`nightEvaluation`)' : t.id === 'camera' ? 'coursework self-tape; `practice.self_tape`' : `coursework: ${Object.entries(TEMPLATE_TASK).filter(([, v]) => v === t.id).map(([k]) => k).join(', ')}`;
    out.push(row([t.label, Object.keys(t.dims).map((d) => DIMENSION_LABEL[d as Dimension]).join(', '), where, t.id === 'performance' ? 'the night’s band: morale, presence, casting, the term’s evaluation' : 'the showing’s band: the meeting’s growth, a classmate’s word', '`tests/evaluation.test.ts` (the guarantee on every profile)']));
  }

  out.push('', '## Exercises: ' + `${EXERCISES.length} of ${EXERCISES.length}`, '', row(['Exercise', 'Trains', 'Source']), '| --- | --- | --- |');
  for (const e of EXERCISES) out.push(row([e.label, (ABILITY_DEFS.find((a) => a.id === e.trains)?.label) ?? TECHNIQUE_LABEL[e.trains as (typeof TECHNIQUES)[number]], e.source]));

  out.push('', '## Profile Sections: 8 of 8', '', row(['Section', 'Reads']), '| --- | --- |');
  for (const [s, r] of [['Identity And Background', 'the character sheet, the bank, the cover'], ['Attributes And Craft', '`abilityOf`, `abilityFull`, `reachOf`, the last five pieces of work’s limits'], ['Techniques', '`craft`, `reachOf`, `MASTERED`'], ['Interests', '`interests`, `engagement.byInterest`, `restOf`'], ['Genres', '`genres`, `engagement.byGenre`, the next part’s play'], ['Current Condition', '`readiness`, `conditionAt`'], ['School Journey', '`school`, `work`'], ['Development History', '`development.history`']] as const) out.push(row([s, r]));

  out.push('', '## Navigation Destinations: 6 of 6', '', row(['Destination', 'Route', 'Where']), '| --- | --- | --- |');
  for (const [n, r, w] of [['Home', '/home', 'the rail’s top, the brand, `h`'], ['Player Profile', '/workspace/profile', 'the rail, your name at its foot, `p`'], ['Calendar', '/workspace/calendar', 'Home’s Calendar section, `c` (kept off the rail by an earlier decision)'], ['School', '/workspace/school', 'the rail, Home’s School panel'], ['Money', '/workspace/bank', 'the rail, Home’s Money panel'], ['Papers', '/workspace/papers', 'the rail, Home’s Papers panel']] as const) out.push(row([n, `\`${r}\``, w]));
  out.push('');
  return out.join('\n');
}
