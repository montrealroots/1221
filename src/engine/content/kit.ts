const ALL_YEAR = ['Spring', 'Summer', 'Autumn', 'Winter'];

/** Anything in the truck. Nothing here hangs on a wardrobe peg. */
const kt = (
  id: string, name: string, brand: string, sub: string, price: number,
  quality: number, depreciation = 0.18, tags: string[] = [],
): RealGood => ({
  id, name, type: 'product', category: 'kit', subcategory: sub, basePrice: price, brand,
  tags: ['kit', sub, ...tags], quality, depreciation, slot: undefined, formality: 0,
  seasons: ALL_YEAR, audience: 'unisex', ...REAL,
});

/**
 * Panavision, which does not sell.
 *
 * The house has rented and never sold its cameras and lenses for its whole
 * history, so there is no retail price to quote and inventing one would be a
 * claim about the world that is not true. These carry a day rate instead, and
 * the floor shows them as rental only.
 */
const pv = (
  id: string, name: string, sub: string, quality: number, tags: string[] = [],
): RealGood => ({
  id, name, type: 'product', category: 'kit', subcategory: sub,
  basePrice: PANAVISION_DAY_RATE[sub] ?? 1_200_00, brand: 'Panavision',
  tags: ['kit', sub, 'rental only', 'day rate', ...tags], quality, depreciation: 0,
  slot: undefined, formality: 0, seasons: ALL_YEAR, audience: 'unisex', ...REAL,
  note: PANAVISION_NOTE,
});

