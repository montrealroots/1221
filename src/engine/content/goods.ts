const V = REFERENCE_VERSION;
const REAL = {
  source: 'calibrated_estimate', confidence: 'high', version: V,
  note: 'Real product, named as public record. The price, quality and wear figures are SLATE\'s own calibration.',
} as const;

export const REAL_GOODS_NOTE = 'A real product. What it costs here is SLATE\'s calibration against local cost of living, not a price from the shop.';

export interface RealGood extends ReferenceRecord {
  type: 'product';
  category: string;
  subcategory: string;
  basePrice: Money;
  brand: string;
  tags: string[];
  quality: number;
  depreciation: number;
  shelfLifeDays?: number;
  unit?: string;
  nourishment?: number;
  slot?: string;
  formality?: number;
  seasons?: string[];
  roomKinds?: string[];
  qualityContribution?: number;
}

function good(spec: Omit<RealGood, 'type' | 'source' | 'confidence' | 'version' | 'note'>): RealGood {
  return { ...spec, type: 'product', ...REAL };
}

